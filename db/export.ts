import { readFile, writeFile } from "node:fs/promises";
import { buildMigrationPlan } from "./plan.ts";
import { parseDirectoryData } from "../shared/directory.ts";

const [schema, students, teachers] = await Promise.all([
  readFile(new URL("./migrations/001_initial.sql", import.meta.url), "utf8"),
  readFile(new URL("./seed/students.json", import.meta.url), "utf8"),
  readFile(new URL("./seed/teachers.json", import.meta.url), "utf8"),
]);
const data = parseDirectoryData({
  schemaVersion: 1,
  students: JSON.parse(students),
  teachers: JSON.parse(teachers),
});
const { queries } = buildMigrationPlan(schema, data);

function literal(value: unknown): string {
  if (value === null) return "NULL";
  if (typeof value === "number" && Number.isFinite(value)) return String(value);
  if (typeof value === "string") return "'" + value.replaceAll("'", "''") + "'";
  throw new Error("Unsupported SQL parameter");
}

const statements = queries.map((query) => {
  const sql = query.text.replace(/\$(\d+)/g, (_, position: string) =>
    literal(query.values?.[Number(position) - 1]),
  );
  return sql.endsWith(";") ? sql : sql + ";";
});
const output =
  "-- Generated by npm run db:export. Execute the complete file in Neon SQL Editor.\nBEGIN;\nSET LOCAL standard_conforming_strings = on;\n\n" +
  statements.join("\n\n") +
  "\n\nCOMMIT;\n";
await writeFile(new URL("./import-initial.sql", import.meta.url), output);
console.log(
  "Generated db/import-initial.sql: " +
    data.students.length +
    " students, " +
    data.teachers.length +
    " teachers.",
);
